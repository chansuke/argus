//! THE list. Every operation any client can perform, declared once. From it the macro
//! generates: the `Handler` trait the host implements, `dispatch` (used by every
//! transport: Tauri IPC, WebSocket, Unix socket), `OPS` metadata, a typed Rust `Client`
//! (the CLI), and the TypeScript client interface (desktop + phone).
//!
//! Kinds: `query` reads, `command` writes, `subscribe` is a query whose value the host
//! pushes again whenever its inputs change (callable once like a query, too).
//! `[agent]` marks the ops an agent run may call through `argus` / MCP (`Caller::may` is
//! the one access rule). Every op is open to the human, on the desktop or a paired phone.

use std::collections::BTreeMap;

use argus_json::Json;

use crate::vm::*;
use crate::wire::Wire;
use crate::{ApiError, Caller, OpAccess, OpInfo, OpKind, Transport};

macro_rules! api {
    (@kind query) => { OpKind::Query };
    (@kind command) => { OpKind::Command };
    (@kind subscribe) => { OpKind::Subscribe };
    (@access agent) => { OpAccess::Agent };
    (@access) => { OpAccess::Human };
    ($( $(#[doc = $doc:literal])* $kind:ident $op:ident ( $input:ty ) -> $output:ty $([$access:ident])? ; )*) => {
        /// Implemented once, by the host. Transports never implement or wrap this.
        pub trait Handler {
            $( $(#[doc = $doc])* fn $op(&mut self, caller: &Caller, input: $input) -> Result<$output, ApiError>; )*
        }

        pub const OPS: &[OpInfo] = &[ $( OpInfo {
            name: stringify!($op),
            kind: api!(@kind $kind),
            access: api!(@access $($access)?),
            doc: concat!($($doc, "\n"),*),
            input_schema: <$input as Wire>::schema,
        } ),* ];

        /// The single entry point for every transport.
        pub fn dispatch<H: Handler>(h: &mut H, caller: &Caller, op: &str, input: &Json) -> Result<Json, ApiError> {
            let info = OPS.iter().find(|o| o.name == op).ok_or_else(|| ApiError::UnknownOp { op: op.to_string() })?;
            if !caller.may(info) {
                return Err(ApiError::Forbidden { op: op.to_string() });
            }
            match op {
                $( stringify!($op) => {
                    let input = <$input as Wire>::from_json(input).map_err(|e| ApiError::BadInput { path: e.path, what: e.what })?;
                    Ok(Wire::to_json(&h.$op(caller, input)?))
                } )*
                _ => unreachable!("op found in OPS"),
            }
        }

        /// Typed client over any transport (used by the `argus` CLI).
        pub struct Client<T: Transport> { pub transport: T }

        impl<T: Transport> Client<T> {
            $( pub fn $op(&mut self, input: &$input) -> Result<$output, ApiError> {
                let out = self.transport.call(stringify!($op), Wire::to_json(input))?;
                <$output as Wire>::from_json(&out).map_err(|e| ApiError::Internal { what: format!("bad reply: {}: {}", e.path, e.what) })
            } )*
        }

        /// Emits `ui/packages/argus-client/src/gen/api.ts`.
        pub fn typescript() -> String {
            let mut decls = BTreeMap::new();
            $( <$input as Wire>::ts_collect(&mut decls); <$output as Wire>::ts_collect(&mut decls); )*
            <ApiError as Wire>::ts_collect(&mut decls);
            let mut out = String::from("// GENERATED by `cargo run -p argus-api --bin argus-ts`. Do not edit.\n\n");
            for d in decls.values() { out.push_str(d); out.push_str("\n\n"); }
            out.push_str("export const OPS = {\n");
            $( out.push_str(&format!("  {}: {{ kind: \"{}\", access: \"{:?}\" }},\n", stringify!($op), stringify!($kind), api!(@access $($access)?))); )*
            out.push_str("} as const;\n\n");
            out.push_str("/** One method per op. Subscriptions return an unsubscribe function. */\nexport interface ArgusApi {\n");
            $(
                let line = match api!(@kind $kind) {
                    OpKind::Subscribe => format!("  {}(input: {}, onValue: (value: {}) => void): () => void;\n",
                        stringify!($op), <$input as Wire>::ts_ref(), <$output as Wire>::ts_ref()),
                    _ => format!("  {}(input: {}): Promise<{}>;\n",
                        stringify!($op), <$input as Wire>::ts_ref(), <$output as Wire>::ts_ref()),
                };
                out.push_str(&line);
            )*
            out.push_str("}\n");
            out
        }
    };
}

api! {
    // -- progress (`overview.queue` is the phone's home screen) --
    subscribe overview(Empty) -> Overview;
    subscribe job(JobRef) -> JobPulse;
    // -- timeline / raw --
    query timeline(TimelineQuery) -> TimelinePage;
    query raw(RawQuery) -> RawPage;
    // -- review & verification --
    subscribe review(JobRef) -> ReviewScreen;
    query presets(Empty) -> Presets;
    /// Asks the chosen models (a preset, or the default) to review the job's head through
    /// one lens. Repeating a `request_id` repeats nothing.
    command request_review(RequestReview) -> RunRefs [agent];
    /// Runs a TLA+ model check, a Lean build, or a device check on the job's head. Repeating
    /// a `request_id` repeats nothing.
    command request_check(RequestCheck) -> RunRef [agent];
    command open_thread(OpenThread) -> Ack;
    command reply(Reply) -> Ack;
    command resolve(Resolve) -> Ack;
    command promote_finding(PromoteFinding) -> Ack;
    command dismiss_finding(DismissFinding) -> Ack;
    query preview_feedback(PreviewFeedback) -> FeedbackText;
    command decide(Decide) -> Ack;
    command merge(MergeJob) -> RunRef;
    // -- jobs & agents --
    command start_jobs(StartJobs) -> Started;
    command send_input(SendInput) -> Ack;
    command answer_permission(AnswerPermission) -> Ack;
    command cancel_run(RunRef) -> Ack;
    /// Adds a task to the job's plan (no `task`; needs a `title`) or changes one (`task`).
    /// An agent may change only the tasks it added.
    command set_task(SetTask) -> TaskSaved [agent];
    /// A Claude Code hook payload from inside a run, kept verbatim in that run's hook log.
    /// Only the run's own agent may send one.
    command hook(HookPayload) -> Ack [agent];
    // -- assets --
    command bookmark(Bookmark) -> Ack;
    query stats(StatsQuery) -> StatsTable;
    query candidates(Empty) -> Candidates;
    command request_insights(RequestInsights) -> RunRef;
    command accept_candidate(AcceptCandidate) -> RunRef;
    command dismiss_candidate(CandidateRef) -> Ack;
}
